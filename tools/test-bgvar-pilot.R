m <- readRDS("artifacts/historical-pilot.rds")
g <- readRDS("artifacts/historical-pilot-irf.rds")
a <- jcer_irf_bgvar(m, "US.stir", horizon = 12)
ref <- array(g$IRF_store[, 1, , ], dim(a$draws))
err <- max(abs(ref - a$draws)); cat("BGVAR raw draw maximum difference:", err, "\n")
stopifnot(err < 1e-10)
qref <- aperm(array(g$posterior[, , 1, ], c(dim(a$draws)[1:2], 5)), c(3, 1, 2))
stopifnot(max(abs(qref - a$quantiles)) < 1e-10)
cat("BGVAR quantiles matched.\n")
